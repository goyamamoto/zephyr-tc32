/*
 * tc32_aes128_encrypt(): one AES-128 block encryption (FIPS-197), key and
 * data in the standard orientation (first byte the most significant).
 *
 * TC32_AES128_SOFTWARE: in software, the S-box a table in flash, the round
 * keys computed on the fly (no key schedule kept), 64 bytes of stack.
 *
 * TC32_AES128_HW_BLOCK: on the TLSR8278's AES block (DS-TLSR8278 15.1,
 * 15.4: 0x540 bit 0 selects decrypt (1) or encrypt (0), bit 1 reads 1 while
 * input data is needed, bit 2 reads 1 when the output data is ready;
 * 0x548-0x54b the input and output data, as four little-endian words;
 * 0x550-0x55f the key, standard orientation), with interrupts off
 * (tlsr827x_irq_save()) so that callers in several threads and interrupts
 * can share it.
 */

